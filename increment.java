public class increment{
    public static void main(String[] args){
        int a=10;
        System.out.println("post increment ="+(a++));
        System.out.println(a);
        System.out.println("pre increment ="+(a));
        System.out.println(a);
        System.out.println("post inncrement ="+(a--));
        System.out.println(a);
        System.out.println("pre increment ="+(--a));
    }
}